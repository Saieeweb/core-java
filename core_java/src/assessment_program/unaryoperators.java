package assessment_program;

public class unaryoperators {

	public static void main(String[] args) {

		int a=5;
		
		System.out.println(++a + --a + a++ + a--);
		System.out.println(a++ + a++ + ++a + --a);
		System.out.println(--a + --a + a++ + a++);
		System.out.println(--a + --a + ++a + ++a);
	}

}
