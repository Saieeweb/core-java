package pratice;

public class Ladder5 {

	public static void main(String[] args) {

 int score=98;
 int run=76;
 
 if 
 (score>=30 && score<=50 && run>=31 && run<=49)


 {
	 System.out.println("low");
 }
 else if 
 (score>=50 && score<=69 && run>=50 && run<=70)


 {
	 System.out.println("medium");
 }
 else if 
 (score>=70 && score<=85 && run>=71 && run<=84)


 {
	 System.out.println("high");
 }
 else if 
 (score>=85 && score<=97 && run>=85 && run<=96)


 {
	 System.out.println("excellent");
 }
 else
	 System.out.println("super excellent");
	}

}
